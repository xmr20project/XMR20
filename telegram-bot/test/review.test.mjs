 const table=new web3.AddressLookupTableAccount({key:new web3.PublicKey(lookup.key),state:{authority:new web3.PublicKey(lookup.authority),deactivationSlot:0xffffffffffffffffn,lastExtendedSlot:1,lastExtendedSlotStartIndex:0,addresses:lookup.addresses.map(k=>new web3.PublicKey(k))}});
